/**
 * Builds every OpenBurner logo asset from flame.json:
 *   node design/brand/build.mjs   (npm run brand)
 *
 * - components/common/brand-mark-paths.ts  path data for <BrandMark />
 * - public/images/openburnerlogo.svg       the mark
 * - public/openburnerlogo.ico: 16 px drawn pixel by pixel (favicon-16.txt), 32/48 from the mark
 * - public/icons/icon-*.png|svg, icon-maskable-512x512.png  app icons
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildFlame, smoothnessProblems } from "./flame.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const k = JSON.parse(fs.readFileSync(path.join(here, "flame.json"), "utf8"));

const problems = smoothnessProblems(k);
if (problems.length) {
  console.error("Flame has kinks:", problems.join("; "));
  process.exit(1);
}

const SMALL = buildFlame(k, true);
// 2 units of padding so antialiasing never trims the circle's edge.
const VB = { x: -2, y: -2, w: 324, h: 381 };
const VIEWBOX = `${VB.x} ${VB.y} ${VB.w} ${VB.h}`;
const ORANGE = k.brand?.orange ?? "#E4572E";
const write = (rel, data) => {
  fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
  fs.writeFileSync(path.join(root, rel), data);
  console.log("wrote", rel);
};

// 1. Paths for the React component
write(
  "components/common/brand-mark-paths.ts",
  `// Generated by design/brand/build.mjs from design/brand/flame.json. Don't edit by hand.\n` +
    `export const FLAME_VIEWBOX = "${VIEWBOX}";\n` +
    `export const FLAME_ASPECT = ${VB.w} / ${VB.h};\n` +
    `export const FLAME_SMALL = "${SMALL}";\n`
);

// 2. Standalone SVGs
const markSvg = (d, color) =>
  `<svg xmlns="http://www.w3.org/2000/svg" overflow="visible" viewBox="${VIEWBOX}" width="${VB.w}" height="${VB.h}"><path d="${d}" fill="${color}" fill-rule="evenodd"/></svg>\n`;
write("public/images/openburnerlogo.svg", markSvg(SMALL, ORANGE));

/** The flame centred (optically) in a square of side `s`. */
function squareSvg(s, { bg = null, fg = ORANGE, scale = 0.9, dy = 0, radius = 0, d = null } = {}) {
  const h = s * scale;
  const w = h * (VB.w / VB.h);
  const pathD = d ?? SMALL;
  const x = (s - w) / 2;
  const y = (s - h) / 2 + dy * s;
  const tile = bg ? `<rect width="${s}" height="${s}" rx="${radius}" fill="${bg}"/>` : "";
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${s} ${s}" width="${s}" height="${s}">${tile}` +
    `<svg overflow="visible" x="${x.toFixed(2)}" y="${y.toFixed(2)}" width="${w.toFixed(2)}" height="${h.toFixed(2)}" viewBox="${VIEWBOX}"><path d="${pathD}" fill="${fg}" fill-rule="evenodd"/></svg></svg>\n`
  );
}


let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.error("sharp isn't installed; skipping PNG and ICO output.");
  process.exit(0);
}
const png = (svg, size) => sharp(Buffer.from(svg), { density: 72 * 4 }).resize(size, size).png().toBuffer();

// 3. App icons: full-bleed tiles (iOS and Android round the corners themselves).
const tile = (s) => squareSvg(s, { bg: ORANGE, fg: "#FFFFFF", scale: k.icon_scale ?? 0.66, dy: k.icon_dy ?? -0.035 });
for (const s of [120, 144, 152, 180, 192, 512]) {
  write(`public/icons/icon-${s}x${s}.png`, await png(tile(s), s));
}
for (const s of [120, 180, 192, 512]) write(`public/icons/icon-${s}x${s}.svg`, tile(s));
// Maskable: the flame stays inside the 80% safe zone of adaptive icons.
write("public/icons/icon-maskable-512x512.png", await png(squareSvg(512, { bg: ORANGE, fg: "#FFFFFF", scale: 0.58, dy: -0.025 }), 512));

// 4. Favicon .ico (PNG-in-ICO), transparent. The 16 px image is drawn pixel by
// pixel (# = full, + = half ink): a downscaled vector blurs the teardrop shut there.
const icoSizes = [16, 32, 48];
function pixelMap(file, hex) {
  const rows = fs.readFileSync(path.join(here, file), "utf8").trim().split("\n");
  const n = rows.length;
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  const buf = Buffer.alloc(n * n * 4);
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      const a = ch === "#" ? 255 : ch === "+" ? 128 : 0;
      buf.set([r, g, b, a], (y * n + x) * 4);
    })
  );
  return sharp(buf, { raw: { width: n, height: n, channels: 4 } }).png().toBuffer();
}
const images = [];
for (const s of icoSizes) {
  images.push(s === 16 ? await pixelMap("favicon-16.txt", ORANGE) : await png(squareSvg(s, { scale: 0.96, d: SMALL }), s));
}
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(images.length, 4);
const dir = Buffer.alloc(16 * images.length);
let offset = 6 + dir.length;
images.forEach((img, i) => {
  const s = icoSizes[i];
  dir.writeUInt8(s === 256 ? 0 : s, i * 16);
  dir.writeUInt8(s === 256 ? 0 : s, i * 16 + 1);
  dir.writeUInt8(0, i * 16 + 2);
  dir.writeUInt8(0, i * 16 + 3);
  dir.writeUInt16LE(1, i * 16 + 4);
  dir.writeUInt16LE(32, i * 16 + 6);
  dir.writeUInt32LE(img.length, i * 16 + 8);
  dir.writeUInt32LE(offset, i * 16 + 12);
  offset += img.length;
});
write("public/openburnerlogo.ico", Buffer.concat([header, dir, ...images]));
